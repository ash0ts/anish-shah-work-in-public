"use client";

import { useEffect, useState } from "react";
import type {
  ConnectorPublicationApprovalOverview,
  ConnectorPublicationApprovalSummary,
  StudioConnectorView,
} from "@/lib/server/connectors";
import styles from "../studio.module.css";
import { ConnectorPermissionControl } from "./ConnectorPermissionControl";
import { formatTimestamp, responseJson } from "./helpers";
import type { ApiResult, Environment } from "./model";
import { studioConnectorActionLabel } from "./action-label";

type StravaState =
  | { phase: "loading" }
  | { phase: "unavailable" }
  | { phase: "error"; message: string }
  | {
      phase: "ready";
      profileUrl: string;
      embedUrl: string | null;
      embedStatus: "available" | "unavailable";
      checkedAt: string | null;
      updatedAt: string | null;
    };

type Props = {
  environment: Environment;
  view: StudioConnectorView;
  approvalOverview: ConnectorPublicationApprovalOverview;
  approval: ConnectorPublicationApprovalSummary | null;
  missingScopes: string[];
  onPermissionUpdated?: (message?: string) => Promise<void>;
  expanded?: boolean;
  onExpandedChange?: (expanded: boolean) => void;
};

const publicStateLabel: Record<StudioConnectorView["publicState"], string> = {
  live: "Live",
  private: "Private",
  needs_action: "Needs action",
  not_connected: "Not connected",
};

export function StravaConnectorControls({
  environment,
  view,
  approvalOverview,
  approval,
  missingScopes,
  onPermissionUpdated,
  expanded,
  onExpandedChange,
}: Props) {
  const [state, setState] = useState<StravaState>({ phase: "loading" });
  const [profileUrl, setProfileUrl] = useState("");
  const [embed, setEmbed] = useState("");
  const [showForm, setShowForm] = useState(!view.configured);
  const [pending, setPending] = useState<
    "save" | "verify" | "disconnect" | null
  >(null);
  const [message, setMessage] = useState<string | null>(null);

  const approvalEntry = approvalOverview.providers.find(
    (entry) => entry.provider === "strava",
  );
  const currentApproval = approvalEntry?.approval ?? approval;
  const currentMissingScopes =
    approvalEntry?.missingScopes ?? missingScopes;

  useEffect(() => {
    let active = true;
    void fetch("/api/studio/connectors/strava/config", { cache: "no-store" })
      .then(async (response) => {
        const result = (await responseJson(response)) as ApiResult & {
          payload?: {
            profileUrl?: string;
            embedUrl?: string | null;
            embedStatus?: "available" | "unavailable";
            checkedAt?: string | null;
            updatedAt?: string;
          };
        };
        if (!active) return;
        if (response.ok && result.payload?.profileUrl) {
          setState({
            phase: "ready",
            profileUrl: result.payload.profileUrl,
            embedUrl: result.payload.embedUrl ?? null,
            embedStatus: result.payload.embedStatus ?? "unavailable",
            checkedAt: result.payload.checkedAt ?? null,
            updatedAt: result.payload.updatedAt ?? null,
          });
          setProfileUrl(result.payload.profileUrl);
          setEmbed(result.payload.embedUrl ?? "");
          setShowForm(false);
        } else if (response.ok && result.status === "unavailable") {
          setState({ phase: "unavailable" });
          setShowForm(true);
        } else {
          setState({
            phase: "error",
            message:
              result.error ??
              "Strava settings could not be checked. Open the row and try again.",
          });
          setShowForm(true);
        }
      })
      .catch(() => {
        if (active) {
          setState({
            phase: "error",
            message:
              "Strava settings could not be checked. Open the row and try again.",
          });
          setShowForm(true);
        }
      });
    return () => {
      active = false;
    };
  }, []);

  async function refreshComposedView(message?: string): Promise<void> {
    await onPermissionUpdated?.(message);
  }

  async function save(): Promise<void> {
    if (!profileUrl.trim()) {
      setMessage("Enter the public Strava athlete profile URL.");
      return;
    }
    setPending("save");
    setMessage(null);
    try {
      const response = await fetch("/api/studio/connectors/strava/config", {
        method: "PUT",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ profileUrl, embed }),
      });
      const result = await responseJson(response);
      if (!response.ok || result.status !== "saved" || !result.profileUrl) {
        setMessage(
          result.error ??
            "Enter the public profile and, optionally, the complete iframe generated by Strava.",
        );
        return;
      }
      setState({
        phase: "ready",
        profileUrl: String(result.profileUrl),
        embedUrl:
          typeof result.embedUrl === "string" ? result.embedUrl : null,
        embedStatus:
          result.embedStatus === "available" ? "available" : "unavailable",
        checkedAt: result.checkedAt ?? null,
        updatedAt: result.updatedAt ?? null,
      });
      setProfileUrl(String(result.profileUrl));
      setEmbed(typeof result.embedUrl === "string" ? result.embedUrl : "");
      setShowForm(false);
      setMessage(
        environment === "local"
          ? "Profile saved locally. Allow public use next; the profile link remains available if the optional feed cannot be framed."
          : "Profile saved. Allow public use next; the profile link remains available if the optional feed cannot be framed.",
      );
      await refreshComposedView(
        environment === "local"
          ? "Strava profile saved locally. Allow public use next."
          : "Strava profile saved. Allow public use next.",
      );
    } catch {
      setMessage("Strava settings were not saved. Try again.");
    } finally {
      setPending(null);
    }
  }

  async function verify(): Promise<void> {
    if (state.phase !== "ready" || !state.embedUrl) {
      setMessage("Save an official Strava feed before verifying it.");
      return;
    }
    setPending("verify");
    setMessage(null);
    try {
      const response = await fetch("/api/studio/connectors/strava/verify", {
        method: "POST",
      });
      const result = await responseJson(response);
      if (!response.ok || result.status !== "verified" || !result.checkedAt) {
        setMessage(
          result.error ??
            "The feed could not be verified. The saved profile fallback is unchanged.",
        );
        return;
      }
      setState((current) =>
        current.phase === "ready"
          ? {
              ...current,
              embedStatus:
                result.embedStatus === "available"
                  ? "available"
                  : "unavailable",
              checkedAt: result.checkedAt ?? null,
            }
          : current,
      );
      setMessage(
        result.embedStatus === "available"
          ? "The feed passed the manual anonymous frame check."
          : "The feed could not be framed. Visitors still receive the profile link.",
      );
      await refreshComposedView();
    } catch {
      setMessage(
        "The feed could not be verified. The saved profile fallback is unchanged.",
      );
    } finally {
      setPending(null);
    }
  }

  async function disconnect(): Promise<void> {
    if (
      !window.confirm(
        `Disconnect Strava? The saved profile, feed, permission, and related history will be deleted${environment === "local" ? " from this local sandbox." : " and Move will be unpublished."}`,
      )
    ) {
      return;
    }
    setPending("disconnect");
    setMessage(null);
    try {
      const response = await fetch("/api/studio/connectors/strava/config", {
        method: "DELETE",
      });
      const result = await responseJson(response);
      if (!response.ok) {
        setMessage(result.error ?? `Request failed (${response.status}).`);
        return;
      }
      setState({ phase: "unavailable" });
      setProfileUrl("");
      setEmbed("");
      setShowForm(true);
      setMessage("Strava disconnected and unpublished.");
      await refreshComposedView();
    } catch {
      setMessage("Strava could not be disconnected. Try again.");
    } finally {
      setPending(null);
    }
  }

  const visiblePublicState =
    state.phase === "error" ? "Needs action" : publicStateLabel[view.publicState];
  const updatedAt =
    state.phase === "ready"
      ? state.updatedAt
      : view.strava?.updatedAt ?? view.snapshot.lastSyncedAt;
  const savedContent =
    state.phase === "ready"
      ? state.embedUrl
        ? "Profile + feed"
        : "Profile saved"
      : view.configured
        ? view.strava?.embedStatus === "available"
          ? "Profile + feed"
          : "Profile saved"
        : "No saved profile";
  const actionLabel = studioConnectorActionLabel(view);

  return (
    <section
      className={styles.connectorPanel}
      aria-labelledby="strava-title"
      data-provider="strava"
    >
      <details
        className={styles.connectorDisclosure}
        open={expanded}
        onToggle={(event) =>
          onExpandedChange?.(event.currentTarget.open)
        }
      >
        <summary className={styles.connectorSummary}>
          <span className={styles.connectorSummaryIdentity}>
            <span>Move</span>
            <strong id="strava-title">Strava</strong>
          </span>
          <span className={styles.connectorSummaryMeta}>
            <span
              className={`${styles.statusPill} ${
                visiblePublicState === "Live"
                  ? styles.status_healthy
                  : visiblePublicState === "Needs action"
                    ? styles.status_error
                    : styles.status_setup_required
              }`}
            >
              {visiblePublicState}
            </span>
            <span>{savedContent}</span>
            <span>{updatedAt ? `Updated ${formatTimestamp(updatedAt)}` : "Not updated"}</span>
          </span>
          <span className={styles.connectorPrimaryAction}>{actionLabel}</span>
        </summary>

        <div className={`${styles.connectorMain} ${styles.connectorDetails}`}>
          {state.phase === "loading" ? (
            <p className={styles.statusGuidance} role="status">
              Checking saved Strava settings…
            </p>
          ) : state.phase === "error" ? (
            <p className={styles.statusGuidance} role="status">
              {state.message}
            </p>
          ) : view.primaryAction === "record_public_permission" ? (
            <p className={styles.statusGuidance} role="status">
              The profile is saved. Record public permission before showing it
              on Move.
            </p>
          ) : state.phase === "ready" && state.embedStatus === "available" ? (
            <p className={styles.statusGuidance}>
              The profile and optional feed are saved. Visitors load the feed
              only after consent.
            </p>
          ) : state.phase === "ready" ? (
            <p className={styles.statusGuidance}>
              The profile is saved. Visitors use it whenever the optional feed
              is unavailable.
            </p>
          ) : (
            <p className={styles.statusGuidance}>
              Save a public athlete profile. An official feed is optional.
            </p>
          )}

          {showForm && state.phase !== "loading" ? (
            <form
              className={styles.credentialForm}
              onSubmit={(event) => {
                event.preventDefault();
                void save();
              }}
            >
              <label className={styles.formField} htmlFor="strava-profile">
                <span>Public athlete profile</span>
                <input
                  id="strava-profile"
                  value={profileUrl}
                  maxLength={2048}
                  inputMode="url"
                  spellCheck={false}
                  onChange={(event) => setProfileUrl(event.target.value)}
                  placeholder="https://www.strava.com/athletes/37597587"
                  required
                />
              </label>
              <label className={styles.formField} htmlFor="strava-embed">
                <span>Official feed iframe · optional</span>
                <textarea
                  id="strava-embed"
                  value={embed}
                  maxLength={8192}
                  rows={3}
                  spellCheck={false}
                  onChange={(event) => setEmbed(event.target.value)}
                  placeholder={
                    '<iframe src="https://www.strava.com/athletes/…/latest-rides/…"></iframe>'
                  }
                />
              </label>
              <div className={styles.formActions}>
                <button
                  type="submit"
                  data-studio-primary-action={
                    view.primaryAction === "connect" ? "" : undefined
                  }
                  disabled={pending !== null}
                >
                  {pending === "save" ? "Checking and saving…" : "Save profile"}
                </button>
                {state.phase === "ready" ? (
                  <button
                    className={styles.textButton}
                    type="button"
                    disabled={pending !== null}
                    onClick={() => {
                      setEmbed(state.embedUrl ?? "");
                      setProfileUrl(state.profileUrl);
                      setShowForm(false);
                    }}
                  >
                    Cancel
                  </button>
                ) : null}
              </div>
            </form>
          ) : null}

          {state.phase === "ready" ? (
            <>
              {view.primaryAction === "record_public_permission" ? (
                <ConnectorPermissionControl
                  provider="strava"
                  providerLabel="Strava"
                  configurationRevision={view.configurationRevision}
                  approval={currentApproval}
                  missingScopes={currentMissingScopes}
                  onUpdated={refreshComposedView}
                />
              ) : null}

              {state.embedUrl ? (
                <div className={styles.actionRow}>
                  <button
                    className={styles.quietButton}
                    type="button"
                    disabled={pending !== null}
                    onClick={() => void verify()}
                  >
                    {pending === "verify" ? "Verifying…" : "Verify now"}
                  </button>
                  <span>
                    Last checked {formatTimestamp(state.checkedAt)}
                  </span>
                </div>
              ) : null}

              <details className={styles.connectorAdvanced}>
                <summary>Advanced / recovery</summary>
                <div className={styles.currentConfig}>
                  <span>Saved profile</span>
                  <code>{state.profileUrl}</code>
                  {state.embedUrl ? <code>{state.embedUrl}</code> : null}
                </div>
                <nav aria-label="Strava setup resources">
                  <a
                    href="https://support.strava.com/en-us/articles/15402053-sharing-your-activities-and-routes-with-a-strava-embed"
                    rel="noreferrer"
                    target="_blank"
                  >
                    Open embed guide
                  </a>{" "}
                  <a
                    href="https://support.strava.com/en-us/articles/15401987-activity-privacy-controls"
                    rel="noreferrer"
                    target="_blank"
                  >
                    Activity privacy
                  </a>
                </nav>
                <p className={styles.recoveryText}>
                  <strong>Use only Strava-generated values.</strong> Save and
                  Verify now are the only actions that perform an anonymous
                  frame check; public reads never recheck Strava.
                </p>
                {view.primaryAction !== "record_public_permission" ? (
                  <ConnectorPermissionControl
                    provider="strava"
                    providerLabel="Strava"
                    configurationRevision={view.configurationRevision}
                    approval={currentApproval}
                    missingScopes={currentMissingScopes}
                    onUpdated={refreshComposedView}
                  />
                ) : null}
                <div className={styles.actionRow}>
                  <button
                    className={styles.quietButton}
                    type="button"
                    disabled={pending !== null}
                    onClick={() => {
                      setMessage(null);
                      setProfileUrl(state.profileUrl);
                      setEmbed(state.embedUrl ?? "");
                      setShowForm(true);
                    }}
                  >
                    Replace settings
                  </button>
                  <button
                    className={styles.quietButton}
                    type="button"
                    disabled={pending !== null}
                    onClick={() => void disconnect()}
                  >
                    {pending === "disconnect" ? "Disconnecting…" : "Disconnect"}
                  </button>
                </div>
              </details>
            </>
          ) : null}

          {message ? (
            <p className={styles.formMessage} role="status">
              {message}
            </p>
          ) : null}
        </div>
      </details>
    </section>
  );
}
