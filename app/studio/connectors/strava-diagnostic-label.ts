import type { StravaDiagnostic } from "@/lib/server/strava/types";

export function stravaDiagnosticLabel(diagnostic?: StravaDiagnostic | null) {
  switch (diagnostic?.result) {
    case "headers_permit":
      return "Headers allow embedding. Open Move and allow Strava to check the actual feed.";
    case "redirected":
      return "Strava redirected the embed. Copy fresh embed code from Strava; the profile link remains available.";
    case "framing_blocked":
      return "Strava blocks framing on this site. Use the profile link; do not bypass that restriction.";
    case "legacy_format":
      return "This activity embed is retired. Copy fresh code from the activity’s Share menu.";
    case "invalid_embed":
      return "The saved embed format is invalid. Replace it with code generated by Strava.";
    case "provider_error":
      return "Strava did not return a usable response. Keep the profile link and verify again later.";
    default:
      return "No current header diagnostic is saved. Verify now before checking the feed in Move.";
  }
}
