import type {
  CopyFieldDefinition,
  CopyPageId,
} from "@/types/copy";

function field(
  surface: string,
  key: string,
  risk: CopyFieldDefinition["risk"],
  maxLength: number,
  options: Partial<Pick<CopyFieldDefinition, "required" | "allowParagraphs">> = {},
): CopyFieldDefinition {
  return {
    key,
    surface,
    risk,
    maxLength,
    required: options.required ?? true,
    allowParagraphs: options.allowParagraphs ?? false,
  };
}

