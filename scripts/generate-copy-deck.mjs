import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildCopyDeck } from "./lib/copy-deck.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, ".generated/site-copy.ts");
const checkOnly = process.argv.includes("--check");
const deck = await buildCopyDeck(root);
const source = `/* Generated by scripts/generate-copy-deck.mjs. Do not edit. */\n` +
  `import type { WorkGroupCopy } from "@/types/copy";\n\n` +
  `export const COPY_VERSION = ${JSON.stringify(deck.copyVersion)} as const;\n\n` +
  `export const SITE_COPY = ${JSON.stringify(deck.pages, null, 2)} as const;\n\n` +
  `export const WORK_GROUP_COPY = ${JSON.stringify(deck.workGroups, null, 2)} as const satisfies Record<string, WorkGroupCopy>;\n`;

if (checkOnly) {
  let existing = "";
  try {
    existing = await readFile(outputPath, "utf8");
  } catch {}
  if (existing !== source) {
    throw new Error("The generated copy module is missing or stale. Run npm run copy:generate.");
  }
  console.log(`Copy deck valid · ${Object.keys(deck.workGroups).length} WorkGroups · ${deck.copyVersion}`);
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, { encoding: "utf8", mode: 0o600 });
  console.log(`Generated .generated/site-copy.ts · ${deck.copyVersion}`);
}
